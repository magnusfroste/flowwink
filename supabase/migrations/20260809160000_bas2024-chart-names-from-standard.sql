-- "Inventarier, verktyg och installationer" is BAS's "Mark".
--
-- Only NAMES change here. Account codes are what journal entries reference, so
-- existing bookkeeping is untouched — a renamed account keeps every line that
-- ever posted to it. What changes is that the label finally tells the truth.
--
-- Codes NOT in BAS 2024 (3010, 3041, 4020, 7020, …) are deliberately left
-- alone: instances may already have posted to them, and deleting an account
-- with history is worse than an account with a non-standard number. They are
-- tracked in KNOWN_NOT_IN_BAS in bas2024-chart.guardrails.test.ts and must only
-- shrink.
--
-- An operator who renamed an account keeps their wording: only rows still
-- carrying our old fabricated name are updated.
-- ============================================================================

