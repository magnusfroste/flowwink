UPDATE public.chart_of_accounts c
   SET account_name = b.account_name, updated_at = now()
  FROM _bas_names b
 WHERE c.locale = 'se-bas2024'
   AND c.account_code = b.account_code
   AND c.account_name <> b.account_name;

DO $$
DECLARE v_n int;
BEGIN
  SELECT count(*) INTO v_n FROM public.chart_of_accounts c JOIN _bas_names b USING (account_code)
   WHERE c.locale = 'se-bas2024' AND c.account_name = b.account_name;
  RAISE NOTICE '% konton stämmer nu med BAS 2024', v_n;
END $$;

